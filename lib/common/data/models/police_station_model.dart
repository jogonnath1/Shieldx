import 'package:latlong2/latlong.dart';

class PoliceStation {
  final String id;
  final String name;
  final String address;
  final String phone;
  final LatLng location;
  final String details;
  final String? jurisdiction;
  final bool isAutoSelected;
  final String thana; // SMP thana name
  final String division;

  const PoliceStation({
    required this.id,
    required this.name,
    required this.address,
    required this.phone,
    required this.location,
    required this.details,
    this.jurisdiction,
    this.isAutoSelected = false,
    this.thana = '',
    this.division = '',
  });

  PoliceStation copyWith({
    String? id,
    String? name,
    String? address,
    String? phone,
    LatLng? location,
    String? details,
    String? jurisdiction,
    bool? isAutoSelected,
    String? thana,
    String? division,
  }) {
    return PoliceStation(
      id: id ?? this.id,
      name: name ?? this.name,
      address: address ?? this.address,
      phone: phone ?? this.phone,
      location: location ?? this.location,
      details: details ?? this.details,
      jurisdiction: jurisdiction ?? this.jurisdiction,
      isAutoSelected: isAutoSelected ?? this.isAutoSelected,
      thana: thana ?? this.thana,
      division: division ?? this.division,
    );
  }

  /// Parses an Overpass API element into a PoliceStation.
  factory PoliceStation.fromOverpass(Map<String, dynamic> el) {
    final tags = el['tags'] as Map<String, dynamic>? ?? {};
    double lat, lon;
    if (el['center'] != null) {
      lat = (el['center']['lat'] as num).toDouble();
      lon = (el['center']['lon'] as num).toDouble();
    } else {
      lat = (el['lat'] as num? ?? 0).toDouble();
      lon = (el['lon'] as num? ?? 0).toDouble();
    }
    final addressParts = [
      tags['addr:housenumber'] ?? '',
      tags['addr:street'] ?? '',
      tags['addr:suburb'] ?? tags['addr:neighbourhood'] ?? '',
      tags['addr:city'] ?? tags['addr:district'] ?? '',
    ].where((s) => s.isNotEmpty).toList();

    return PoliceStation(
      id: '${el['id']}',
      name: tags['name'] ??
          tags['name:en'] ??
          tags['official_name'] ??
          'Police Station',
      address: addressParts.isEmpty
          ? 'Address not available'
          : addressParts.join(', '),
      phone: tags['phone'] ??
          tags['contact:phone'] ??
          tags['contact:mobile'] ??
          '',
      location: LatLng(lat, lon),
      details: tags['description'] ??
          'Official police station providing security and public services.',
      jurisdiction: tags['operator:area'] ?? tags['addr:subdistrict'] ?? '',
      thana: tags['addr:subdistrict'] ?? '',
      division: '',
    );
  }
}

